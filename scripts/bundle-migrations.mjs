/**
 * Concatenates the migrations into one script for pasting into the Supabase
 * SQL editor, so applying the schema needs no CLI and no database password.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE = join('supabase', 'migrations')
const OUT_DIR = join('supabase', '.generated')
const OUT = join(OUT_DIR, 'apply_all.sql')

const files = readdirSync(SOURCE).filter((f) => f.endsWith('.sql')).sort()

const body = files
  .map((file) => {
    const banner = `-- ${'='.repeat(70)}\n-- ${file}\n-- ${'='.repeat(70)}\n`
    return banner + readFileSync(join(SOURCE, file), 'utf8')
  })
  .join('\n\n')

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(
  OUT,
  `-- Kickback schema bundle. Generated by scripts/bundle-migrations.mjs.\n` +
    `--\n` +
    `-- Paste into Supabase -> SQL Editor -> New query and run.\n` +
    `--\n` +
    `-- SAFE TO RE-RUN, and safe to run again after a run that stopped part-way.\n` +
    `-- Every migration carries its own begin/commit, so a failure leaves the\n` +
    `-- migrations before it committed and rolls back only the one that failed;\n` +
    `-- re-running then picks up from a known state rather than needing repair.\n` +
    `-- tests/db/bundle.test.ts applies this file twice, three times, and on top\n` +
    `-- of partial histories, so the claim above is checked rather than hoped.\n\n` +
    body,
)

console.log(`wrote ${OUT} from ${files.length} migrations`)
