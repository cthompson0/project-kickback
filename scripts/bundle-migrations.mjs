/**
 * Concatenates the migrations into one script for pasting into the Supabase
 * SQL editor, so applying the schema needs no CLI and no database password.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE = join('supabase', 'migrations')
const OUT_DIR = join('supabase', '.generated')
const OUT = join(OUT_DIR, 'apply_all.sql')

const files = readdirSync(SOURCE).filter((f) => f.endsWith('.sql')).sort()

const body = files
  .map((file) => {
    const banner = `-- ${'='.repeat(70)}\n-- ${file}\n-- ${'='.repeat(70)}\n`
    return banner + readFileSync(join(SOURCE, file), 'utf8')
  })
  .join('\n\n')

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(
  OUT,
  `-- Kickback schema bundle. Generated by scripts/bundle-migrations.mjs.\n` +
    `-- Paste into Supabase -> SQL Editor -> New query and run. Safe to re-run.\n\n` +
    body,
)

console.log(`wrote ${OUT} from ${files.length} migrations`)
